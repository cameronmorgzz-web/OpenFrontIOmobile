"""Run every Phase-2 calculation and write calc/RESULTS.md + calc/results.json.

    python -m calc.run_all
"""

from __future__ import annotations

import json
import math
from dataclasses import replace
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from cad import params as P  # noqa: E402
from calc import ballistics as B  # noqa: E402
from calc import button, latch, motor, stress  # noqa: E402
from calc.arm_dynamics import simulate_swing  # noqa: E402
from calc.design import (GEAR_EFF, GEAR_RATIO, H_CATCH, MOTOR, RANGES, aero, launch_angle,  # noqa: E402
                         mass_props, release_height, setting)

OUT = Path(__file__).resolve().parent
PLOTS = OUT / "plots"

# Targets from the brief
TARGETS = dict(v_catch_max=4.0, peak_max=2.3, latency_max=2.5, cycle_max=8.0, sf_min=2.5,
               batt_months_min=3.0, cap_force=(3.0, 5.0))


def main() -> dict:
    PLOTS.mkdir(exist_ok=True)
    mp, mp_src = mass_props()
    res: dict = dict(mass_props=mp, mass_props_source=mp_src, motor=MOTOR, gear_ratio=GEAR_RATIO)
    lines = ["# Phase 2 — analytical results (generated by `python -m calc.run_all`)", "",
             f"Mass properties: **{mp_src}**. Every number below is produced by the code in `calc/`; "
             "equations are in each module's docstring, sources in `research/SOURCES.md`.", ""]

    # ---------------- Ballistics ----------------
    h0 = release_height()
    ang = launch_angle()
    lines += ["## 1. Ballistics (quadratic drag, `calc/ballistics.py`)", "",
              f"Release height {h0:.3f} m (pivot {P.PIVOT_H} mm + arm {P.ARM_L} mm at alpha="
              f"{P.ALPHA_RELEASE_NOMINAL_DEG} deg), catch height {H_CATCH} m, Cd={aero().cd}, A={aero().area:.5f} m2.",
              "", "| range m | launch angle | v0 m/s | catch speed m/s | peak height m | flight s | vacuum min catch speed m/s | min-catch-speed angle (drag) |",
              "|---|---|---|---|---|---|---|---|"]
    bal = {}
    for R in RANGES:
        v = B.speed_for_range(R, ang, h0, aero(), H_CATCH)
        s = B.fly(v, ang, h0, aero(), H_CATCH, keep=True)
        opt = B.min_catch_speed_angle(R, h0, aero(), H_CATCH)
        vac = B.vacuum_min(R, H_CATCH - h0)
        bal[R] = dict(v0=v, v_catch=s.v_catch, peak=s.peak_z, t=s.t_flight, opt_angle=opt.angle_deg,
                      opt_v_catch=opt.v_catch, vac_v_catch=vac[1])
        lines.append(f"| {R:.0f} | {ang:.0f} deg | {v:.2f} | {s.v_catch:.2f} | {s.peak_z:.2f} | {s.t_flight:.2f} | "
                     f"{vac[1]:.2f} | {opt.angle_deg:.1f} deg ({opt.v_catch:.2f} m/s) |")
        plt.plot(s.traj[0], s.traj[1], label=f"{R:.0f} m: v0={v:.2f} m/s, catch {s.v_catch:.2f} m/s")
    r4 = B.max_range_for_catch_speed(TARGETS["v_catch_max"], H_CATCH - h0)
    res["ballistics"] = bal
    res["max_range_at_4ms"] = r4
    plt.axhline(2.3, ls="--", c="r", lw=0.8, label="peak limit 2.3 m")
    plt.axhline(0.9, ls=":", c="k", lw=0.8, label="catch height")
    plt.gca().set_aspect("equal"), plt.xlabel("x [m]"), plt.ylabel("z [m]"), plt.legend(fontsize=7)
    plt.title("Trajectories at 48 deg launch (drag)"), plt.savefig(PLOTS / "trajectories.png", dpi=130), plt.close()
    lines += ["", f"**Target conflict (physics):** the lowest possible catch speed for a given range is the "
              f"minimum-energy shot; in vacuum `v_c^2 = g(sqrt(R^2+dh^2) - dh)`. With dh = {H_CATCH-h0:.2f} m, "
              f"catch speed <= 4 m/s is only reachable up to R = **{r4:.2f} m**. At 4 m the floor is "
              f"{bal[4.0]['vac_v_catch']:.2f} m/s (vacuum) / {bal[4.0]['opt_v_catch']:.2f} m/s (with drag). "
              "No launcher can meet both 4 m and 4 m/s; we fly the minimum-catch-speed arc (48 deg detent is "
              f"within {abs(ang-bal[4.0]['opt_angle']):.1f} deg of optimum) — see DECISIONS.md D2.", ""]

    # ---------------- Arm dynamics ----------------
    lines += ["## 2. Spring -> arm -> can (`calc/arm_dynamics.py`)", "",
              f"{P.N_SPRINGS} x {P.SPRING.part} (R={P.SPRING.rate} N/mm, F0={P.SPRING.f0} N, Fn={P.SPRING.f_max} N, "
              f"sn={P.SPRING.s_max} mm), drum r={P.DRUM_R} mm, swing {P.SWING_DEG} deg, I_arm={mp['I_arm']:.4f} kg m2.", "",
              "| range | preload x_rest mm | max ext mm | F_max/spring N (% Fn) | spring E J | can KE J | arm KE J | gravity J | friction J | efficiency | release m/s | swing ms | peak can accel m/s2 (g) | min back-wall force N |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    sets = {}
    for R in RANGES:
        st = setting(R)
        m, sw = st["model"], st["swing"]
        sets[R] = st
        xmax = m.extension(0) * 1000
        F = m.spring_force(0)
        lines.append(f"| {R:.0f} m | {m.x_rest*1000:.1f} | {xmax:.1f} | {F:.0f} ({F/P.SPRING.f_max:.0%}) | "
                     f"{sw.energy_spring:.2f} | {sw.energy_can_kin:.2f} | {sw.energy_arm_kin:.2f} | {sw.energy_grav:.2f} | "
                     f"{sw.energy_friction:.2f} | {sw.efficiency:.2f} | {sw.v_release:.2f} | {sw.t_swing*1000:.0f} | "
                     f"{sw.a_peak:.0f} ({sw.a_peak/9.81:.1f} g) | {sw.min_back_wall_force:.1f} |")
    res["arm"] = {R: dict(x_rest_mm=s["model"].x_rest * 1000, v0=s["v0"], E_spring=s["swing"].energy_spring,
                          eff=s["swing"].efficiency, a_peak=s["swing"].a_peak, t_swing=s["swing"].t_swing,
                          F_max=s["model"].spring_force(0), omega=s["swing"].omega)
                  for R, s in sets.items()}
    preload_span = (sets[5.0]["model"].x_rest - sets[3.0]["model"].x_rest) * 1000
    lines += ["", f"Preload adjustment needed 3->5 m: **{preload_span:.1f} mm** of anchor travel "
              f"(available {P.PRELOAD_ADJ_RANGE[1]-P.PRELOAD_ADJ_RANGE[0]:.0f} mm on the M6 adjusters; "
              f"M6 pitch 1.0 mm -> {preload_span:.0f} turns). Sensitivity at 4 m: "
              f"{_sens(sets[4.0]):.3f} m range per mm preload.", ""]
    # 500 ml
    c500 = P.CANS["500"]
    lines += ["### 500 ml can (CAN_SIZE='500')", ""]
    res["can500"] = {}
    for R in (3.0, 4.0, 5.0):
        try:
            st = setting(R, c500)
            F = st["model"].spring_force(0)
            ok = F <= P.SPRING_LOAD_LIMIT * P.SPRING.f_max and st["model"].x_rest * 1000 <= P.PRELOAD_ADJ_RANGE[1]
            res["can500"][R] = dict(x_rest_mm=st["model"].x_rest * 1000, F=F, ok=ok)
            lines.append(f"- {R:.0f} m: preload {st['model'].x_rest*1000:.1f} mm, spring {F:.0f} N "
                         f"({F/P.SPRING.f_max:.0%} Fn) -> {'OK' if ok else 'NOT ALLOWED (exceeds 85% Fn)'}")
        except Exception as e:  # noqa: BLE001
            lines.append(f"- {R:.0f} m: not reachable ({e})")
    lines.append("")

    # swing plot
    sw = sets[4.0]["swing"]
    fig, ax = plt.subplots(1, 2, figsize=(9, 3.2))
    ax[0].plot(sw.t * 1000, np.degrees(sw.phi)), ax[0].set_xlabel("t [ms]"), ax[0].set_ylabel("swing [deg]")
    ax[1].plot(sw.t * 1000, sw.phid * P.ARM_L / 1000), ax[1].set_xlabel("t [ms]"), ax[1].set_ylabel("can speed [m/s]")
    fig.suptitle("Arm swing, 4 m setting"), fig.tight_layout(), fig.savefig(PLOTS / "swing_4m.png", dpi=130)
    plt.close(fig)

    # ---------------- Motor ----------------
    lines += ["## 3. Cocking motor (`calc/motor.py`)", "",
              f"{MOTOR['name']}: no-load {MOTOR['w0_rpm']} rpm, rated {MOTOR['rated_torque']:.2f} N m @ "
              f"{MOTOR['rated_rpm']} rpm, derived stall {MOTOR['stall_torque']:.2f} N m / {MOTOR['stall_current']:.1f} A, "
              f"R={MOTOR['R_winding']:.2f} ohm. Printed stage {P.PINION_TEETH}:{P.RING_TEETH} = {GEAR_RATIO:.1f}, eta={GEAR_EFF}.", "",
              "| range | t_cock s | t_retract s | peak motor torque N m (% stall) | peak current A | peak ring torque N m | press->launch s | min fire->fire s | I_rms (8 s cycle) / rated |",
              "|---|---|---|---|---|---|---|---|---|"]
    res["motor"] = {}
    for R in RANGES:
        c = motor.cock(sets[R]["model"])
        lat = motor.latency(c)
        th = motor.thermal(c)
        cyc = motor.cycle_time(c)
        res["motor"][R] = dict(**{k: v for k, v in c.items()}, latency=lat["total"], cycle=cyc, I_rms=th["I_rms"])
        lines.append(f"| {R:.0f} m | {c['t_cock']:.2f} | {c['t_retract']:.2f} | {c['Tm_peak']:.2f} ({c['Tm_peak_frac_stall']:.0%}) | "
                     f"{c['I_peak']:.2f} | {c['ring_torque_peak']:.1f} | **{lat['total']:.2f}** | {cyc:.2f} | "
                     f"{th['I_rms']:.2f}/{th['I_rated']} = {th['ratio']:.2f} |")
    lines += ["", f"Latency budget: button wake+TX {motor.T_BUTTON_WAKE_TX}s, radio {motor.T_RADIO}s, "
              f"cock, feed {motor.T_FEED}s, settle {motor.T_SETTLE}s, latch trip {motor.T_SEAR_TRIP}s (the ring returns to park "
              "during RESET, after the shot, so it is not in the latency path); "
              "the 1.5 s warning starts with the motor (cocking is fully enclosed) and FIRE is blocked until it has run >= 1.5 s.", ""]

    # ---------------- Latch ----------------
    T5 = sets[5.0]["model"].spring_torque(0)
    la = latch.analyse(T5)
    res["latch"] = la
    lines += ["## 4. Ring latch / servo trip (`calc/latch.py`)", "",
              f"Cocked torque at 5 m: {T5:.2f} N m -> catch force {la['F_catch']:.0f} N on the 608 roller. "
              "Over-centre (toggle) latch on the cocking ring; steel nose dowel; servo MG996R.", "",
              "| case | e mm (closing) | closing moment N m | finger force worst N | servo torque needed best/nom/worst N m | MG996R margin worst | (MG90S margin) | trip rotation deg |",
              "|---|---|---|---|---|---|---|---|"]
    for k in ("min_e", "nom", "max_e"):
        d = la[k]
        t = d["tau_trip"]
        lines.append(f"| {k} | {d['e']*1000:.1f} | {d['M_close']:.3f} | {d['F_finger_worst']:.1f} | "
                     f"{t['best']:.3f}/{t['nom']:.3f}/{t['worst']:.3f} | **{d['servo_margin_worst']:.1f}x** | "
                     f"{d['mg90s_margin_worst']:.1f}x | {d['trip_rotation_deg']:.1f} |")
    lines += ["", f"Self-locking at e_min: **{la['self_locking']}** (holds with power off). The toggle cuts the force "
              f"needed to release by {la['reduction_vs_direct']:.0f}x versus pulling a plain hook off the roller "
              f"({la['plain_hook_servo_force']:.0f} N). An MG90S would not have a 2x margin, so the latch uses an MG996R; "
              f"safety-pin shear if the servo is forced with the pin in: {latch.safety_pin_load(T5):.1f} N.", ""]

    # ---------------- Stress ----------------
    c5 = motor.cock(sets[5.0]["model"])
    ring_T = c5["ring_torque_peak"]
    Ft_gear = ring_T / (P.GEAR_MODULE * P.RING_TEETH / 2 / 1000)
    checks, sx = stress.run(sets[5.0], sets[4.0], ring_T, Ft_gear, mp)
    res["stress"] = [dict(part=c.part, case=c.case, stress=c.stress, sf=c.sf, sf_static=c.sf_static,
                          sf_fatigue=c.sf_fatigue, sf_creep=c.sf_creep) for c in checks]
    res["stress_extra"] = sx
    lines += ["## 5. Hand stress checks (`calc/stress.py`)", "",
              f"PETG: sut_xy={P.PETG.sut_xy} MPa, sut_z={P.PETG.sut_z} MPa (Z = {P.PETG.sut_z/P.PETG.sut_xy:.0%} of XY), "
              f"fatigue S/UTS={P.PETG.fatigue_ratio_1e3} at 1e3 cycles, sustained-stress limit {P.PETG.creep_limit_ratio:.0%} UTS. "
              f"Absorber impact speed at 5 m: {sx['abs_impact_v']:.2f} m/s (AC1416-1 max {stress.ABS_V_MAX} m/s).", "",
              "| part | case | load | stress MPa | dir | SF static | SF fatigue | SF creep | min SF | pass |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for c in checks:
        accidental = "DRY FIRE" in c.case
        need = 1.0 if accidental else TARGETS["sf_min"]
        f = lambda v: "-" if v is None else f"{v:.1f}"  # noqa: E731
        lines.append(f"| {c.part} | {c.case} | {c.load} | {c.stress:.2f} | {c.direction} | {f(c.sf_static)} | "
                     f"{f(c.sf_fatigue)} | {f(c.sf_creep)} | **{c.sf:.1f}** | {'PASS' if c.sf >= need else 'FAIL'}"
                     f"{' (accidental, need >=1)' if accidental else ''} |")
    lines.append("")

    # ---------------- Button ----------------
    bl = button.battery_life()
    cf = button.cap_force()
    res["button"] = dict(life=bl, cap=cf)
    lines += ["## 6. Button (`calc/button.py`)", "", "| sleep consumer | uA |", "|---|---|"]
    lines += [f"| {k} | {v*1e6:.1f} |" for k, v in button.SLEEP.items()]
    lines += [f"| **total** | **{bl['I_sleep_uA']:.1f}** |", "",
              f"Per press: {bl['mAh_per_press']*1000:.1f} uAh; per day (5 presses): {bl['mAh_per_day']:.3f} mAh + "
              f"self-discharge {bl['self_discharge_mAh_day']:.3f} mAh -> **{bl['months']:.1f} months** on "
              f"{button.CAPACITY_MAH:.0f} mAh x {button.USABLE_FRACTION:.0%} usable. {button.SLEEP_NOTE}.", "",
              f"Cap springs: 4 x k={cf['k_each']:.3f} N/mm -> rest {cf['F_rest']:.2f} N, actuation **{cf['F_actuate']:.2f} N**, "
              f"bottomed {cf['F_bottom']:.2f} N; solid length {cf['solid_len']:.1f} mm < compressed {cf['min_len']:.1f} mm (no coil bind).", ""]

    # ---------------- Gate 2 summary ----------------
    gate = []
    gate.append(("Peak height <= 2.3 m (5 m shot)", bal[5.0]["peak"], bal[5.0]["peak"] <= TARGETS["peak_max"]))
    gate.append(("Catch speed <= 4 m/s at 4 m", bal[4.0]["v_catch"], bal[4.0]["v_catch"] <= TARGETS["v_catch_max"]))
    gate.append(("Press->launch <= 2.5 s at 4 m", res["motor"][4.0]["latency"], res["motor"][4.0]["latency"] <= 2.5))
    gate.append(("Press->launch <= 2.5 s at 5 m", res["motor"][5.0]["latency"], res["motor"][5.0]["latency"] <= 2.5))
    gate.append(("Cycle <= 8 s", res["motor"][5.0]["cycle"], res["motor"][5.0]["cycle"] <= 8))
    gate.append(("Motor < 90% stall at 5 m", c5["Tm_peak_frac_stall"], c5["Tm_peak_frac_stall"] < 0.9))
    gate.append(("Servo trip margin >= 2 (worst mu, max e)", la["max_e"]["servo_margin_worst"], la["max_e"]["servo_margin_worst"] >= 2))
    gate.append(("Latch self-locking at min e", float(la["min_e"]["e"] * 1000), la["self_locking"]))
    nonacc = [c for c in checks if "DRY FIRE" not in c.case]
    gate.append(("Min SF (non-accidental) >= 2.5", min(c.sf for c in nonacc), min(c.sf for c in nonacc) >= 2.5))
    gate.append(("Dry-fire min SF >= 1 and absorber energy <= 20 J",
                 min(c.sf for c in checks if "DRY FIRE" in c.case), min(c.sf for c in checks if "DRY FIRE" in c.case) >= 1
                 and sx["E_dry"] <= stress.ABS_ENERGY_MAX))
    gate.append(("Battery >= 3 months", bl["months"], bl["months"] >= 3))
    gate.append(("Cap actuation 3-5 N", cf["F_actuate"], 3 <= cf["F_actuate"] <= 5))
    gate.append(("Springs <= 85% Fn at 5 m (330 ml)", sets[5.0]["model"].spring_force(0) / P.SPRING.f_max,
                 sets[5.0]["model"].spring_force(0) <= P.SPRING_LOAD_LIMIT * P.SPRING.f_max))
    res["gate2"] = [dict(name=n, value=float(v), ok=bool(o)) for n, v, o in gate]
    lines += ["## Gate 2 checklist", "", "| check | value | result |", "|---|---|---|"]
    lines += [f"| {n} | {v:.3f} | {'PASS' if o else '**FAIL**'} |" for n, v, o in gate]
    lines.append("")
    (OUT / "RESULTS.md").write_text("\n".join(lines))
    (OUT / "results.json").write_text(json.dumps(_jsonable(res), indent=1))
    print("\n".join(lines))
    return res


def _sens(st) -> float:
    m = st["model"]
    v1 = simulate_swing(replace(m, x_rest=m.x_rest + 0.001)).v_release
    h0 = release_height()
    r0 = B.fly(st["v0"], launch_angle(), h0, aero(), H_CATCH).range_m
    r1 = B.fly(v1, launch_angle(), h0, aero(), H_CATCH).range_m
    return r1 - r0


def _jsonable(o):
    if isinstance(o, dict):
        return {str(k): _jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_jsonable(v) for v in o]
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    if isinstance(o, float) and (math.isnan(o) or math.isinf(o)):
        return None
    return o


if __name__ == "__main__":
    main()
